function placeDistricts(lat, lng, names) {
  return names.map((name, i) => {
    if (name === 'Центр') return { name, lat, lng };
    if (name === 'Весь населённый пункт') return { name, lat: lat - 0.01, lng: lng + 0.012 };
    const angle = (2 * Math.PI * i) / Math.max(names.length, 1);
    const radius = names.length > 6 ? 0.028 : 0.016;
    return {
      name,
      lat: +(lat + radius * Math.cos(angle)).toFixed(4),
      lng: +(lng + radius * Math.sin(angle) * 1.7).toFixed(4),
    };
  });
}

export const PLACES = Object.entries(BELARUS).flatMap(([oblast, settlements]) =>
  Object.entries(settlements).map(([settlement, districts]) => {
    const [lat, lng] = SETTLEMENT_COORDS[settlement] || [53.9, 27.5];
    const pinned = CITY_DISTRICT_COORDS[settlement];
    const districtPlaces = pinned
      ? districts.map((name) => {
          const [dLat, dLng] = pinned[name] || [lat, lng];
          return { name, lat: dLat, lng: dLng };
        })
      : placeDistricts(lat, lng, districts);
    return { oblast, settlement, lat, lng, districts: districtPlaces };
  }),
);

export function getPlace(oblast, settlement) {
  return PLACES.find((p) => p.oblast === oblast && p.settlement === settlement) || null;
}

