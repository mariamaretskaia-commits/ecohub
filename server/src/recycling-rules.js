/**
 * Правила «что нельзя сдавать в обычную переработку».
 *
 * Матчинг пунктов в point-kinds.js умеет только виды приёма (paper/glass/...).
 * Этого мало: «чеки» и «салфетки» по категории похожи на бумагу, «зеркало» —
 * на стекло, а «мягкая игрушка» — на текстиль. Здесь мы отсекаем такие вещи
 * до выбора пункта и объясняем причину.
 *
 * Важно: правила не блокируют публикацию объявлений. Они влияют только на
 * подбор пунктов приёма («Разобрать вещи» и «Куда сдать»).
 */

function norm(s) {
  return String(s || '')
    .toLocaleLowerCase('ru')
    .replace(/ё/g, 'е')
    .replace(/[\s,.;:!?"'«»()\-–—/\\+]+/g, ' ')
    .trim()
    .replace(/\s+/g, ' ');
}

function any(...patterns) {
  return (value, category) => patterns.some((p) => (
    typeof p === 'function' ? p(value, category) : p.test(value)
  ));
}

const TEXTILE_RE = /(?:^| )(одежд|куртк|пальто|плащ|джинс|футболк|рубашк|брюк|юбк|платье|свитер|кофт|шарф|шапк|обув|кроссовк|ботинк|сапог|носк|бель|текстил|постельн|полотенц)/;

function textileContext(value, category) {
  return category === 'Одежда' || TEXTILE_RE.test(value);
}

