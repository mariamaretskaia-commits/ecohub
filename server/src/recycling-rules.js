const BATTERY_RE = /(?:^| )батарейк|аккумулятор|(?:^| )акб(?: |$)|элемент[а-я]* питания/;

/** Точные материалы, где название важнее широкой категории. */
const MATERIAL_RULES = [
  {
    test: /(?:^| )нож(?:а|у|ом|е|и|ей|ам|ами|ах)?(?: |$)/,
    kinds: ['metal'],
  },
  {
    test: /консервн[а-я]* банк/,
    kinds: ['metal'],
  },
];

function ruleMatches(rule, value, category) {
  return typeof rule.test === 'function'
    ? rule.test(value, category)
    : rule.test.test(value);
}

/**
 * @param {string|null} name
 * @param {string} [category]
 * @returns {{blocked:true,reason:string,advice:string}|{kinds:string[],exclusive:true}|null}
 */
export function recyclingRuleFor(name, category) {
  const value = norm(name);
  if (!value) return null;

  const blocked = BLOCK_RULES.find((rule) => ruleMatches(rule, value, category));
  if (blocked) {
    return { blocked: true, reason: blocked.reason, advice: blocked.advice };
  }

  if (BATTERY_RE.test(value)) {
    return { kinds: ['hazardous'], exclusive: true };
  }

  const material = MATERIAL_RULES.find((rule) => ruleMatches(rule, value, category));
  if (material) {
    return { kinds: [...material.kinds], exclusive: true };
  }

  return null;
}

/** Готовая строка для UI: причина + что делать. */
export function recyclingNoteFor(name, category) {
  const rule = recyclingRuleFor(name, category);
  if (!rule?.blocked) return null;
  return [rule.reason, rule.advice].filter(Boolean).join(' ');
}
