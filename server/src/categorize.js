/** Служебные слова-«мусор», не влияющие на категорию (количество/состояние). */
const STOP_WORDS = new Set([
  'пара', 'пары', 'пар', 'штука', 'штуки', 'штук', 'набор', 'набора', 'наборы',
  'комплект', 'комплекта', 'комплекты', 'несколько', 'примерно', 'около',
  'новая', 'новый', 'новые', 'новую', 'старая', 'старый', 'старые', 'старую',
  'б', 'у']);

function normalize(s) {
  return String(s || '')
    .toLocaleLowerCase('ru')
    .replace(/ё/g, 'е')
    .replace(/\b\d+(?:[.,]\d+)?\b/g, ' ')
    .replace(/[\s,.;:!?"'«»()\-––/\\+]+/g, ' ')
    .trim()
    .replace(/\s+/g, ' ')
    .split(' ')
    .filter((w) => !STOP_WORDS.has(w))
    .join(' ');
}

export function categorizeByRules(name) {
  const n = normalize(name);
  if (!n) return 'Другое';
  for (const [phrase, cat] of PRECEDENCE) {
    if (n.includes(phrase)) return cat;
  }
  const words = n.split(' ').filter(Boolean);
  for (const cat of RULE_ORDER) {
    const stems = RULES[cat] || [];
    if (stems.some((stem) => words.some((w) => w.startsWith(stem)))) return cat;
  }
  return 'Другое';
}

function validCategory(c, categories) {
  return categories.includes(c) ? c : null;
}

function readCategories(nodes, list, categories) {
  const map = new Map();
  if (Array.isArray(nodes)) {
    for (const el of nodes) {
      if (!el || typeof el !== 'object') continue;
      const cat = validCategory(String(el.category || '').trim(), categories);
      if (!cat) continue;
      const name = String(el.name || '').trim();
      const idx = list.findIndex((n) => n === name || normalize(n) === normalize(name));
      if (idx !== -1) map.set(list[idx], cat);
    }
    return map;
  }
  if (!nodes || typeof nodes !== 'object') return map;
  const keyIndex = new Map(list.map((name, i) => [normalize(name), i]));
  for (const [rawKey, rawValue] of Object.entries(nodes)) {
    const cat = validCategory(String(rawValue || '').trim(), categories);
    if (!cat) continue;
    const idx = keyIndex.get(normalize(String(rawKey)));
    if (idx != null) map.set(list[idx], cat);
  }
  return map;
}

