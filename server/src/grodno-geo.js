export function locateByAddress(address) {
  const text = String(address || '').toLowerCase();
  return STREET_GEO.find((row) => row.match.some((part) => text.includes(part))) || null;
}

export function shortStreet(address) {
  return String(address || '')
    .replace(/^г\.\s*гродно,?\s*/i, '')
    .replace(/\s+/g, ' ')
    .trim();
}
